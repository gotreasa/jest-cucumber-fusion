// Writes test-d/index.test-d.cts: the type tests, as a CommonJS twin. In a .cts file TypeScript
// resolves the package's "require" condition, so the twin checks dist/index.d.cts where
// test-d/index.test-d.ts reaches src/index.d.ts (issue #58). Generated, not committed, so the
// assertions have one source.
//
// Run by pretest-d, after the build, and never by the build itself: prepack runs the build, and
// the release must not depend on the type tests.
//
// The source opens with a reference directive naming the twin, so a run without it fails with
// ts(6053) rather than quietly checking half. The twin drops that line: a file cannot reference
// itself (ts(1006)).
import fs from "fs";
import path from "path";

const typeTests = path.resolve(import.meta.dirname, "..", "test-d");
const reference = '/// <reference path="./index.test-d.cts" />\n';

const source = fs.readFileSync(path.join(typeTests, "index.test-d.ts"), "utf8");
if (!source.startsWith(reference))
  throw new Error(
    `test-d/index.test-d.ts must open with ${reference.trim()}, so a run without the CommonJS twin fails instead of checking half.`,
  );

fs.writeFileSync(
  path.join(typeTests, "index.test-d.cts"),
  "// Generated by scripts/build-type-tests.js from index.test-d.ts. Do not edit.\n" +
    source.slice(reference.length),
);
